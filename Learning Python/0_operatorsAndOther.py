# These are the list of operators, function, and expression for python3


x = 20
y = 7
a = True
b = False

# Arithmatic Operators 
# The output will be integer
print(x + y)	# Adds two operands.
print(x - y)	# Subtracts the right operand from the left.
print(x * y)	# Multiplies two operands.
print(x / y)	# Divides the left operand by the right (results in a float).
print(x % y)	# Returns the remainder of the division.
print(x ** y) 	# Raises the left operand to the power of the right.
print(x // y)	# Divides and returns the integer part of the result (discards the fractional part).

# Comparison (relational) Operators
# The ouput will be True or False (Boolean)
print(x == y)	# Returns True if both operands are equal.
print(x != y)	# Returns True if the operands are not equal.
print(x > y)	# Returns True if the left operand is greater than the right.
print(x < y)	# Returns True if the left operand is less than the right.
print(x >= y)	# Returns True if the left operand is greater than or equal to the right.
print(x <= y)	# Returns True if the left operand is less than or equal to the right.

# Logical Operators
# The output will be True and False (Boolean)
print(a and b)	# Returns True if both statements are true.
print(a or b)	# Returns True if at least one statement is true.
print(not a)	# Reverses the result; returns False if the result is true.

# Assignment Operator
# It used to assign value to variable
x = 20	# set value 5 to variable x
print(x)
x += 3	# x = x + 3
print(x)
x -= 3	# x = x - 3
print(x)
x *= 3	# x = x * 3
print(x)
x /= 3	# x = x / 3
print(x)
x %= 3	# x = x % 3
print(x)
x //= 3	# x = x // 3
print(x)
x **= 3	# x = x ** 3
print(x)
x &= 3	# x = x & 3
print(x)
x ^= 3	# x = x ^ 3
print(x)
x >>= 3 # x = x >> 3
print(x)
x <<= 3	# x = x << 3
